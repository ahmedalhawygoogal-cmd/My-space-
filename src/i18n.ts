export type I18nKey = keyof typeof ar

const dict: Record<Lang, Record<I18nKey, string>> = {
  ar, en, fr, de, es, tr, it, ru, zh, ja, ko, pt, hi, ur, fa, nl, pl, id,
}

export function t(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const table = dict[lang]
  let s = (table && table[key]) || dict.en[key] || key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  }
  return s
}
